const nz = (v) => num(v, { zeroIsNull: true });
const no9999 = (v) => (v == null || v <= -9999 ? null : v);

// The Alberta Geological Survey's geothermal resource layers share one schema: wells that
// reach a formation, with its depth, average temperature and heat-in-place estimates.
function albertaGeothermal({ key, service, layer, formation, probe }) {
  return {
    key,
    country: "CA",
    state: "AB",
    label: `Alberta wells reaching the ${formation} - formation depth and temperature (geothermal resource assessment)`,
    probe,
    agency: "Alberta Geological Survey / Alberta Energy Regulator",
    url: `https://services2.arcgis.com/jQV6VMr2Loovu7GU/arcgis/rest/services/${service}/FeatureServer/${layer}`,
    pageMax: 2000,
    idKind: "id",
    idLabel: "UWI (e.g. '100010105619W503')",
    extent: [-120.1, 48.9, -109.9, 60.1],
    license: "Open Government Licence - Alberta",
    caveat: `AGS geothermal resource assessment: one record per well that reaches the ${formation}, with the formation's top and base depth (m TVD), average temperature (deg C) and heat-in-place / power estimates. No well name, operator or dates.`,
    searchFields: { api: "UWI", field: "Geol_unit" },
    normalize: (a, g) => ({
      api: a.UWI,
      wellName: null,
      operator: null,
      field: a.Geol_unit,
      ...geomFirst(a, g, "Lat_NAD83", "Long_NAD83"),
      kbElevationM: no9999(a.KB_el_masl),
      formationTopTVD: no9999(a.T_TVD_m),
      formationBaseTVD: no9999(a.B_TVD_m),
      depthUnit: "m",
      formationTempC: no9999(a.Avg_temp_C),
      heatInPlacePJperKm2: no9999(a.HIP_PJ_km2),
      thermalPower: no9999(a.Therm_pwr),
      electricPower: no9999(a.Eltr_pwr),
    }),
  };
}

// Manitoba's well list: a shapefile (NAD83 UTM 14N) refreshed by the Petroleum Branch.
async function loadManitoba() {
  const zip = await fetchBuffer("https://www.gov.mb.ca/iem/petroleum/gis/wells.zip", { timeoutMs: 60_000 });
  return readDbf(unzipEntry(zip, ".dbf")).map((a) => {
    const p = a.EASTING && a.NORTHING ? utmToLatLon(a.EASTING, a.NORTHING, 14) : null;
    return { attrs: a, geometry: p ? { x: p.longitude, y: p.latitude } : null };
  });
}

